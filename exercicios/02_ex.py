"""
Peça ao usuário dois números com input(), converta para float e mostre:
A soma
A subtração
A multiplicação
A divisão
A potência do primeiro pelo segundo
"""
n1 = float(input("Digite o primeiro número: "))
n2 = float(input("Digite o segundo número: "))
soma = n1 + n2
subtracao = n1 - n2
multiplicacao = n1 * n2
divisao = n1 / n2
potencia = n1**n2

print(soma)
print(subtracao)
print(multiplicacao)
print(divisao)
print(potencia)